#!/usr/bin/env python3
"""
pdf-invoice-stat v2.4.7 · 铁路电子客票特殊规则

【背景】
铁路电子客票的"退票费"（含"改签费""手续费"等价外费用）不属于运输服务价款，
按规定不征收增值税。原 v2.4.x 实现把退票费按 6% 普通应税服务拆税，导致：
    价税合计 ¥33.00 → 错误拆成 金额 ¥31.13 + 税额 ¥1.87
正确口径（价外费用）：
    价税合计 ¥33.00 → 金额 ¥33.00 + 税额 ¥0.00，税率列留空

【设计原则】
本模块为纯函数，只接收 result 字典与页面文本，不做任何解析。
所有规则集中在此，主代码仅保留一行钩子调用，便于测试与回滚。
"""


def apply_train_ticket_rules(result, text):
    """
    应用铁路电子客票特殊规则（就地修改并返回 result）

    规则 R1｜退票费属价外费用，不计增值税
        触发：页面文本含「退票费」
        动作：金额 = 价税合计，税额 = 0，税率列留空
        依据：《铁路旅客运输规程》及增值税价外费用不征税口径

    规则 R2｜票价维持 9% 计税（不改动）
        触发：默认
        动作：无（本模块不干预），确保与原实现完全一致

    返回：result（同一字典对象）
    """
    if not isinstance(result, dict):
        return result

    total = result.get('total') or 0.0

    # ── R1：退票费 = 价外费用，不征增值税 ──────────────────────
    if text and '退票费' in text and total > 0:
        result['amount'] = float(total)
        result['tax'] = 0.0
        result['rate'] = ''          # 税率列留空（与"多税率留空"设计规范一致）
        result['item_name'] = '火车票-退票费'

    # ── R2：票价不做任何干预 ──────────────────────────────
    return result


