export const dictLookup = (name) => {
  const key = String(name || '').replace(/[\s·・]/g, '');
  if (DICT[key]) return DICT[key];
  // 宽松匹配：菜名包含词典键（长出的部分不超过 3 字，避免「鸡」命中「宫保鸡丁」）
  for (const k in DICT) {
    if (key.length >= 2 && key.includes(k) && key.length - k.length <= 3) return DICT[k];
  }
  return null;
};

