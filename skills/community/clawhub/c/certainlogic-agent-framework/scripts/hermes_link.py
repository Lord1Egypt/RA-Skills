#!/usr/bin/env python3
"""
Hermes Integration Linker — write Hermes integration spec + link Brain API.

Usage:
    python3 hermes_link.py                           # auto-detect and link
    python3 hermes_link.py --brain-url http://127.0.0.1:8000
"""
import argparse
import os
import sys
from pathlib import Path

SKILL_DIR = Path(__file__).resolve().parent.parent
WORKSPACE = Path.cwd()


def write_hermes_spec(brain_url):
    """Write the Hermes integration spec."""
    spec_path = WORKSPACE / "hermes-integration.md"
    content = f"""# Hermes Integration — Auto-linked via certainlogic-agent-framework

## Brain API
- URL: {brain_url}
- Purpose: Token reduction, hallucination detection, factual consistency
- Linked: {__import__('datetime').datetime.now().isoformat()}

## Agent Framework
- Skill: certainlogic-agent-framework
- Self-model: Cypher Tempre timechain (if initialized)
- Quality gates: assumptions_check, production_gate, secret_guard

## Usage
Include in Hermes spec preamble:

```python
import sys
sys.path.insert(0, "{SKILL_DIR}/scripts")
```
"""
    spec_path.write_text(content)
    print(f"Written: {spec_path}")


def write_brain_env(brain_url):
    """Write .brain_env for Brain API connectivity."""
    env_path = WORKSPACE / ".brain_env"
    content = f"# Brain API environment — auto-generated by hermes_link.py\n"
    content += f"BRAIN_URL={brain_url}\n"
    content += f"TIMECHAIN_URL=http://127.0.0.1:8080\n"

    if env_path.exists():
        existing = env_path.read_text()
        if "BRAIN_URL" not in existing:
            env_path.write_text(existing + "\n" + content)
            print(f"Appended to {env_path}")
        else:
            print(f"{env_path} already has BRAIN_URL — skipping")
    else:
        env_path.write_text(content)
        print(f"Created {env_path}")


def main():
    parser = argparse.ArgumentParser(description="Link agent framework with Hermes")
    parser.add_argument("--brain-url", default="http://127.0.0.1:8000")
    args = parser.parse_args()

    print("=== Hermes Integration Linker ===\n")
    write_hermes_spec(args.brain_url)
    write_brain_env(args.brain_url)
    print("\nDone. Hermes is linked to the agent framework.")


if __name__ == "__main__":
    main()