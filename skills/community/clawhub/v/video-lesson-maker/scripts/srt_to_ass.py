#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""SRT → ASS 字幕转换（根治 ffmpeg subtitles 滤镜的 PlayRes 缩放坑）。

## 背景（本项目 V01~V10 + 项目2 V01~V03 的重大教训）

ffmpeg 的 `subtitles` 滤镜对 **SRT 输入**使用 libass 默认脚本分辨率
`PlayResX=384 / PlayResY=288`。当实际画面不是 384x288 时，`force_style`
里的 FontSize 会按比例缩放：

    scale = frame_height / PlayResY

实测：1080x600 画面上 FontSize=32 → 实际渲染约 **73px 高**（600/288≈2.08 倍），
一条 28 字的中文字幕宽约 28*66≈1850px，直接撑爆 1080 宽画面、左右被裁切。
这就是"生成的视频字体太大、超出了视频界面"的根因。

## 解法

显式写出与**目标画面尺寸一致**的 PlayResX/PlayResY，使 Style 中的 FontSize
就等于**画面像素值**，缩放因子恒为 1.0，完全可控。再用 ffmpeg 的 `ass`
滤镜（而非 `subtitles`）烧录。

## 用法

    python srt_to_ass.py --srt 同步字幕.srt --out subs.ass --width 1080 --height 600
    ffmpeg -y -i 成片.mp4 -vf "ass='subs.ass'" -c:v libx264 -crf 21 -pix_fmt yuv420p -c:a copy out.mp4

## 字号经验值（按画面高度比例，实测不溢出）

    1080x600（本项目出图规格）：FontSize 26，28 字宽约 728px，安全边距充足
    通用：max_chars * FontSize + 2*MarginL <= width
"""
import argparse
import os
import re
import sys


def parse_srt(path):
    txt = open(path, encoding="utf-8").read()
    cues = []
    for block in re.split(r"\n\s*\n", txt.strip()):
        lines = [l for l in block.strip().splitlines() if l.strip()]
        if len(lines) < 3:
            continue
        tc = lines[1]
        m = re.match(r"(\d+):(\d+):(\d+)[,.](\d+)\s*-->\s*(\d+):(\d+):(\d+)[,.](\d+)", tc)
        if not m:
            continue
        g = [int(x) for x in m.groups()]
        start = g[0] * 3600 + g[1] * 60 + g[2] + g[3] / 1000.0
        end = g[4] * 3600 + g[5] * 60 + g[6] + g[7] / 1000.0
        cues.append((start, end, "".join(lines[2:])))
    return cues


def ass_time(t):
    """秒 → ASS 时间 H:MM:SS.cc（百分秒）"""
    t = max(0.0, t)
    h = int(t // 3600)
    m = int((t % 3600) // 60)
    s = t % 60
    cs = int(round((s - int(s)) * 100))
    if cs == 100:
        cs = 0
        s += 1
    return "%d:%02d:%02d.%02d" % (h, m, int(s), cs)


def esc(text):
    """ASS 文本转义：花括号、换行"""
    text = text.replace("{", r"\{").replace("}", r"\}")
    return text.replace("\n", r"\N")


def bgr(color_hex):
    """RRGGBB → ASS &HAABBGGRR（本项目统一给 &H00 不透明）"""
    c = color_hex.lstrip("#")
    r, g, b = int(c[0:2], 16), int(c[2:4], 16), int(c[4:6], 16)
    return "&H00%02X%02X%02X" % (b, g, r)


def main():
    ap = argparse.ArgumentParser(description="SRT → ASS（显式 PlayRes，字号=画面像素）")
    ap.add_argument("--srt", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--width", type=int, required=True, help="画面宽（PlayResX）")
    ap.add_argument("--height", type=int, required=True, help="画面高（PlayResY）")
    ap.add_argument("--font", default="SimHei")
    ap.add_argument("--font-size", type=int, default=26, help="字号（=画面像素，经验 26）")
    ap.add_argument("--outline", type=float, default=2.5)
    ap.add_argument("--shadow", type=float, default=1.0)
    ap.add_argument("--margin-v", type=int, default=36)
    ap.add_argument("--margin-lr", type=int, default=40)
    ap.add_argument("--primary", default="FFFFFF", help="文字色 RRGGBB")
    ap.add_argument("--outline-color", default="000000", help="描边色 RRGGBB")
    a = ap.parse_args()

    cues = parse_srt(a.srt)
    if not cues:
        print("[err] SRT 无有效字幕", file=sys.stderr)
        return 1

    # 自检：最长字幕是否溢出可用宽度
    usable = a.width - 2 * a.margin_lr
    worst = max(cues, key=lambda c: len(c[2]))
    # 中日韩字符按全宽、ASCII 按半宽估算宽度
    def width_est(s):
        return sum(a.font_size if ord(ch) > 0x2E7F else a.font_size * 0.55 for ch in s)
    we = width_est(worst[2])
    flag = "OK" if we <= usable else "!! 超宽，请减小 --font-size 或增宽画面"
    print("字幕 %d 条；最长 %d 字，估算宽 %.0fpx / 可用 %dpx  %s"
          % (len(cues), len(worst[2]), we, usable, flag))

    style = ("Style: Default,%s,%d,%s,%s,%s,&H80000000,-1,0,0,0,100,100,0,0,"
             "1,%s,%s,2,%d,%d,%d,1"
             % (a.font, a.font_size, bgr(a.primary), bgr(a.primary),
                bgr(a.outline_color), a.outline, a.shadow,
                a.margin_lr, a.margin_lr, a.margin_v))

    lines = [
        "[Script Info]",
        "; Generated by srt_to_ass.py (explicit PlayRes to avoid libass scaling)",
        "Title: synced subtitles",
        "ScriptType: v4.00+",
        "WrapStyle: 0",
        "ScaledBorderAndShadow: yes",
        "YCbCr Matrix: None",
        "PlayResX: %d" % a.width,
        "PlayResY: %d" % a.height,
        "",
        "[V4+ Styles]",
        "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, "
        "OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, "
        "ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, "
        "MarginL, MarginR, MarginV, Encoding",
        style,
        "",
        "[Events]",
        "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text",
    ]
    for st, en, tx in cues:
        lines.append("Dialogue: 0,%s,%s,Default,,0,0,0,,%s"
                     % (ass_time(st), ass_time(en), esc(tx)))

    with open(a.out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("已写出 -> %s (PlayResX=%d PlayResY=%d FontSize=%d)"
          % (a.out, a.width, a.height, a.font_size))
    return 0


if __name__ == "__main__":
    sys.exit(main())
