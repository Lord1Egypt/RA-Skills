#!/bin/bash
# =============================================================================
# preflight.sh — 动手前强制自检
# Rule: 不搜案例不动手，不预检不动手
# =============================================================================
# 用法: 在动手前运行 ./preflight.sh "你要做的事"
# 示例: ./preflight.sh "部署一个新的cron定时任务"
# =============================================================================

set -e

TASK="${1:-}"
if [ -z "$TASK" ]; then
    echo "❌ 用法: ./preflight.sh \"任务描述\""
    echo "   示例: ./preflight.sh \"修改Nginx配置\""
    exit 1
fi

echo "═══════════════════════════════════════════════════════"
echo "  🛡️  preflight — 动手前强制自检"
echo "  任务: $TASK"
echo "═══════════════════════════════════════════════════════"
echo ""

# ── 检查 1: 搜过案例了吗？ ──────────────────────────────
echo "┌─ ✅ 检查项 1/4 ──────────────────────────────────┐"
echo "│  搜索过成功案例或已知方案了吗？                      │"
echo "│  (不要凭记忆/直觉，先搜再定)                         │"
echo "└────────────────────────────────────────────────────┘"
echo -n "  已搜索确认？(y/n): "
read -r ANSWER1
if [ "$ANSWER1" != "y" ]; then
    echo "  ⛔ 停！先搜案例再动手。"
    echo "  参考: 在搜索引擎或团队知识库中搜同类问题"
    exit 1
fi
echo "  ✅ 通过"
echo ""

# ── 检查 2: 有回滚方案吗？ ─────────────────────────────
echo "┌─ ✅ 检查项 2/4 ──────────────────────────────────┐"
echo "│  失败了知道怎么回滚吗？                               │"
echo "│  (有没有备份？有没有回退路径？)                        │"
echo "└────────────────────────────────────────────────────┘"
echo -n "  回滚方案明确？(y/n): "
read -r ANSWER2
if [ "$ANSWER2" != "y" ]; then
    echo "  ⛔ 停！没有回滚方案不准动手。"
    echo "  先写好回滚步骤再操作"
    exit 1
fi
echo "  ✅ 通过"
echo ""

# ── 检查 3: 方案稳定吗？ ──────────────────────────────
echo "┌─ ✅ 检查项 3/4 ──────────────────────────────────┐"
echo "│  方案经过论证或测试了吗？                               │"
echo "│  (不拍脑袋，动手验证可行性)                             │"
echo "└────────────────────────────────────────────────────┘"
echo -n "  已测试/论证？(y/n): "
read -r ANSWER3
if [ "$ANSWER3" != "y" ]; then
    echo "  ⛔ 停！先小范围测试再大规模操作。"
    exit 1
fi
echo "  ✅ 通过"
echo ""

# ── 检查 4: 影响范围清楚吗？ ─────────────────────────
echo "┌─ ✅ 检查项 4/4 ──────────────────────────────────┐"
echo "│  操作的影响范围清楚吗？                                  │"
echo "│  (改了哪里？会影响谁？多久能恢复？)                     │"
echo "└────────────────────────────────────────────────────┘"
echo -n "  影响范围明确？(y/n): "
read -r ANSWER4
if [ "$ANSWER4" != "y" ]; then
    echo "  ⛔ 停！不清楚影响范围就是在赌。"
    exit 1
fi
echo "  ✅ 通过"
echo ""

# ── 全部通过 ──────────────────────────────────────────
echo "═══════════════════════════════════════════════════════"
echo "  ✅ 全部通过！可以开始干了。"
echo "  任务: $TASK"
echo "═══════════════════════════════════════════════════════"
echo ""
echo "完成后记得:"
echo "  1. 如果成功 → 写一笔到每日日志"
echo "  2. 如果失败 → 写进 LEARNINGS.md"
echo "  3. 如果学到了新东西 → 更新 SKILL.md"
echo ""
